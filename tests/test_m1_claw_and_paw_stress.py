def test_claw_math_10000_in_vivo_randomized():
    """
    Empirically test claw orientation math across 10,000 randomized in-vivo claws
    generated by the biological creature generator (500 creatures * 20 claws).
    Asserts dot product with forward axis > 0.60 and dz < 0 unconditionally.
    """
    random.seed(42)

    total_claws_tested = 0
    passed_claws = 0
    failed_claws = []

    min_fwd_dot = float("inf")
    max_fwd_dot = float("-inf")
    max_dz = float("-inf")
    min_dz = float("inf")

    for i in range(500):
        scale = random.uniform(0.1, 5.0)
        c_front = random.uniform(0.05, 0.25)
        c_hind = random.uniform(0.04, 0.20)
        curve_fac = random.uniform(0.35, 0.55)
        sw_front = random.uniform(0.25, 0.60)
        sw_hind = random.uniform(0.25, 0.60)

        cfg = UrsineAnatomyConfig(
            scale=scale,
            claw_length_front=c_front,
            claw_length_hind=c_hind,
            claw_curve_factor=curve_fac,
            stance_width_front=sw_front,
            stance_width_hind=sw_hind,
        )

        res = generate_bear_base_mesh(cfg)
        assert len(res.claws) == 20, f"Expected 20 claws, got {len(res.claws)}"

        for claw in res.claws:
            total_claws_tested += 1
            dot = claw.forward_dot
            dz = claw.downward_pitch

            min_fwd_dot = min(min_fwd_dot, dot)
            max_fwd_dot = max(max_fwd_dot, dot)
            max_dz = max(max_dz, dz)
            min_dz = min(min_dz, dz)

            if dot > 0.60 and dz < 0.0:
                passed_claws += 1
            else:
                failed_claws.append((i, claw.claw_id, dot, dz))

    assert total_claws_tested == 10000
    assert len(failed_claws) == 0, f"Failures in 10,000 in-vivo claws: {failed_claws[:5]}"
    assert min_fwd_dot > 0.60, f"Min forward dot product {min_fwd_dot} <= 0.60"
    assert max_dz < 0.0, f"Max dz {max_dz} >= 0.0"


def test_claw_math_10000_direct_randomized():
    """
    Empirically test claw orientation math across 10,000 direct add_curved_claw
    invocations with randomized yaw angles, scales, splays, and curvatures.
    Asserts dot product with forward axis > 0.60 and dz < 0 unconditionally.
    """
    random.seed(1337)

    tested = 0
    passed = 0
    failed = []

    min_dot = float("inf")
    max_dot = float("-inf")
    max_dz = float("-inf")
    min_dz = float("inf")

    for j in range(10000):
        length = random.uniform(0.01, 2.0)
        base_radius = random.uniform(0.005, 0.1) * length
        curve_factor = random.uniform(0.30, 0.60)
        splay_factor = random.uniform(-0.35, 0.35)
        base_pos = (random.uniform(-5, 5), random.uniform(-5, 5), random.uniform(0, 5))

        # Forward direction with randomized yaw in [-pi, pi]
        yaw = random.uniform(-math.pi, math.pi)
        # In character horizontal plane:
        fwd_dir = (math.sin(yaw), -math.cos(yaw), 0.0)
        down_dir = (0.0, 0.0, -1.0)

        geom = MeshGeometry()
        claw_verts = geom.add_curved_claw(
            base_pos=base_pos,
            forward_dir=fwd_dir,
            downward_dir=down_dir,
            length=length,
            base_radius=base_radius,
            curve_factor=curve_factor,
            segments=6,
            radial_segments=8,
            splay_factor=splay_factor,
        )

        assert len(claw_verts) > 0
        tip_vertex = geom.vertices[claw_verts[-2]]
        vx = tip_vertex[0] - base_pos[0]
        vy = tip_vertex[1] - base_pos[1]
        vz = tip_vertex[2] - base_pos[2]
        vlen = math.sqrt(vx * vx + vy * vy + vz * vz)
        assert vlen > 0.005

        d_unit = (vx / vlen, vy / vlen, vz / vlen)
        dot = d_unit[0] * fwd_dir[0] + d_unit[1] * fwd_dir[1] + d_unit[2] * fwd_dir[2]
        dz = d_unit[2]

        tested += 1
        min_dot = min(min_dot, dot)
        max_dot = max(max_dot, dot)
        min_dz = min(min_dz, dz)
        max_dz = max(max_dz, dz)

        if dot > 0.60 and dz < -1e-6:
            passed += 1
        else:
            failed.append((j, length, curve_factor, splay_factor, dot, dz))

    assert tested == 10000
    assert len(failed) == 0, f"Failures in 10,000 direct claw tests: {failed[:5]}"
    assert min_dot > 0.60, f"Min dot product {min_dot} <= 0.60"
    assert max_dz < 0.0, f"Max dz {max_dz} >= 0.0"


def test_plantigrade_geometry_adversarial():
    """
    Adversarially test plantigrade paw geometry:
    1. Calcaneus heel Z coordinate is flush with ground (z = 0).
    2. Plantar/palmar pads reside below bone structures (cz_pad < cz_box).
    3. All 5 digital pads per paw are distinct, non-coincident, and have positive separation.
    """
    scales = [0.25, 0.5, 1.0, 1.5, 2.5, 5.0]

    for s in scales:
        cfg = UrsineAnatomyConfig(scale=s)
        res = generate_bear_base_mesh(cfg)
        mesh = res.mesh

        # 1. Hind paw calcaneus heel ground contact in limbs group
        # Hind foot box is in vertex group 'limbs'
        limbs_indices = res.vertex_groups["limbs"]
        hind_box_verts = [
            mesh.vertices[i] for i in limbs_indices
            if mesh.vertices[i][1] > 0.25 * s and mesh.vertices[i][2] <= 0.10 * s
        ]
        assert len(hind_box_verts) > 0, f"No hind paw foot box vertices found for scale {s}"

        min_z_box = min(v[2] for v in hind_box_verts)
        # Assert calcaneus heel bottom is flush with ground (z = 0 within float epsilon)
        assert abs(min_z_box - 0.0) < 1e-6, (
            f"Calcaneus heel min Z {min_z_box} is not flush with ground 0.0 (scale={s})"
        )

        # Check calcaneus posterior contact point (max y at min z = 0)
        # In pes box: center y is 0.46*s - 0.13*s = 0.33*s, size y is 0.26*s, so max y is 0.46*s
        heel_pts = [
            v for v in hind_box_verts
            if abs(v[2] - 0.0) < 1e-6 and abs(v[1] - 0.46 * s) < 1e-5
        ]
        assert len(heel_pts) > 0, f"No calcaneus heel ground contact vertices at posterior edge for scale {s}"

        # 2. Check plantar and palmar pads positioned below bone structures
        pads_hind_indices = res.vertex_groups["pads_hind"]
        pads_front_indices = res.vertex_groups["pads_front"]
        assert len(pads_hind_indices) > 0
        assert len(pads_front_indices) > 0

        pads_hind_verts = [mesh.vertices[i] for i in pads_hind_indices]
        pads_front_verts = [mesh.vertices[i] for i in pads_front_indices]

        # For hind paw: plantar pad center is at z = 0.01 * s, box center is at z = 0.04 * s
        # Plantar pad bottom extends to -0.01 * s, providing the underside cushion
        min_z_pad_hind = min(v[2] for v in pads_hind_verts)
        max_z_pad_hind = max(v[2] for v in pads_hind_verts)
        assert min_z_pad_hind < 0.0, f"Plantar pad bottom {min_z_pad_hind} should extend below ground line"
        assert max_z_pad_hind <= 0.0301 * s, f"Plantar pad top {max_z_pad_hind} must be below upper dorsal bone box {0.08*s}"

        # 3. Check 5 digital pads per paw are distinct, non-coincident, and have positive separation
        for is_front, paw_prefix in [(True, "Front"), (False, "Hind")]:
            for side in ["L", "R"]:
                paw_name = f"{paw_prefix}_{side}"
                paw_claws = [c for c in res.claws if c.paw == paw_name]
                assert len(paw_claws) == 5, f"Paw {paw_name} has {len(paw_claws)} digits, expected 5"

                # Check pairwise distance between digital claw bases / pad anchors
                for d1 in range(5):
                    for d2 in range(d1 + 1, 5):
                        p1 = paw_claws[d1].base_pos
                        p2 = paw_claws[d2].base_pos
                        dist = math.sqrt(sum((a - b) ** 2 for a, b in zip(p1, p2)))
                        expected_min_dist = 0.035 * s
                        assert dist >= expected_min_dist, (
                            f"Digital pads {d1} and {d2} on paw {paw_name} collided! Dist {dist} < {expected_min_dist}"
                        )


def test_adversarial_boundary_analysis():
    """
    Explore and assert theoretical and empirical boundaries of the claw orientation equation:
    dot = 1 / sqrt(1 + C^2 + S^2)
    dz = -C / sqrt(1 + C^2 + S^2)
    """
    # 1. Critical boundary where dot <= 0.60:
    # 1 / sqrt(1 + C^2 + S^2) <= 0.60 <=> C^2 + S^2 >= 16/9 ≈ 1.7778 <=> sqrt(C^2 + S^2) >= 1.3333
    critical_radius = 4.0 / 3.0

    # 2. Maximum biological parameter configuration in MorphoMesh Ursine engine:
    # C = 0.48, max |S| = 0.1056
    r_bio = math.sqrt(0.48 ** 2 + 0.1056 ** 2)
    dot_bio = 1.0 / math.sqrt(1.0 + r_bio ** 2)
    assert dot_bio > 0.89, f"Biological dot product {dot_bio} too low"

    # Safety margin calculation:
    # Safety margin = (critical_radius - r_bio) / critical_radius
    safety_margin = (critical_radius - r_bio) / critical_radius
    assert safety_margin > 0.60, f"Safety margin {safety_margin} too low"

    # 3. Assert upward pitch if C <= 0
    dz_neg_c = -(-0.1) / math.sqrt(1.0 + 0.01)
    assert dz_neg_c > 0.0, "Negative curvature must produce upward pitch (dz > 0)"
